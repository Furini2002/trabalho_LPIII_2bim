    private void buttonFiltrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonFiltrarActionPerformed
        //setando as variaveis para o filtro
        Double valorMin = Double.parseDouble(textValorMin.getText().replaceAll("\\.", "").replaceAll(",", "."));

        try {
            ProdutoDAO produtoDao = new ProdutoDAO();

            produtos = produtoDao.buscarProdutoValorMinimo(valorMin);

            ProdutoTableModel tableModel = (ProdutoTableModel) tableProdutos.getModel();
            tableModel.clear();
            tableModel.addList(produtos);

        } catch (RuntimeException e) {
            JOptionPane.showMessageDialog(this, "Erro ao buscar produtos: " + e.getMessage());
        }

    }//GEN-LAST:event_buttonFiltrarActionPerformed

