    public ProdutoFiltroValor() {
        // configurando o Locale para o Brasil (usando "," como separador decimal e "." como separador de milhares)
        Locale locale = new Locale("pt", "BR");
        DecimalFormat decimalFormat = (DecimalFormat) NumberFormat.getInstance(locale);
        decimalFormat.applyPattern("#,##0.00"); // Padrão internacional

        // Cria o NumberFormatter com o DecimalFormat configurado
        NumberFormatter numFormatter = new NumberFormatter(decimalFormat);
        numFormatter.setFormat(decimalFormat);
        numFormatter.setAllowsInvalid(false); // Impede valores inválidos

        // Cria a fábrica de formatadores
        DefaultFormatterFactory dfFactory = new DefaultFormatterFactory(numFormatter);

        initComponents();

        tableProdutos.setModel(tableModel);

        // Configura o campo monetário com o formatador
        textValorMin.setFormatterFactory(dfFactory);

        buscarProdutos();
    }

    private void buscarProdutos() {
        // Cria a tela de carregamento, passando a janela atual como pai
        LoadingDialog loadingDialog = new LoadingDialog(this);

        // Cria o SwingWorker para carregar os dados em background
        SwingWorker<List<Produto>, Void> worker = new SwingWorker<>() {
            @Override
            protected List<Produto> doInBackground() throws Exception {
                ProdutoDAO prodDao = new ProdutoDAO();
                return prodDao.findAll();
            }

            @Override
            protected void done() {
                try {
                    List<Produto> produtosRetornados = get();
                    ProdutoTableModel tableModel = (ProdutoTableModel) tableProdutos.getModel();
                    tableModel.clear();
                    tableModel.addList(produtosRetornados);
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(ProdutoFiltroValor.this, "Erro ao buscar produtos: " + e.getMessage());
                } finally {
                    // Fecha o diálogo de carregamento
                    loadingDialog.dispose();
                }
            }
        };

        // Inicia o carregamento dos dados
        worker.execute();

        // Exibe o diálogo de carregamento (modal)
        loadingDialog.setVisible(true);
    }

