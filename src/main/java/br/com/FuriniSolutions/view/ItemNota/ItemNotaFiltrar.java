    private void buttonFiltrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonFiltrarActionPerformed
        //setando as variaveis para o filtro
        String produto = textProduto.getText();
        Integer quantidade = null;

        if (!textQuantidade.getText().equalsIgnoreCase("")) {
            quantidade = Integer.parseInt(textQuantidade.getText());
        }

        try {
            ItemNotaDAO itemDao = new ItemNotaDAO();

            itens = itemDao.filtrarItensPorProdutoEQuantidade(produto, quantidade);

            ItemNotaTableModel tableModel = (ItemNotaTableModel) tableItensNota.getModel();
            tableModel.clear();
            tableModel.addList(itens);

        } catch (RuntimeException e) {
            JOptionPane.showMessageDialog(this, "Erro ao buscar itens de nota: " + e.getMessage());
        }

    }//GEN-LAST:event_buttonFiltrarActionPerformed

