    private void buscarItens() {

        // Cria a tela de carregamento, passando a janela atual como pai
        LoadingDialog loadingDialog = new LoadingDialog(this);

        // Cria o SwingWorker para carregar os dados em background
        SwingWorker<List<ItemNota>, Void> worker = new SwingWorker<>() {
            @Override
            protected List<ItemNota> doInBackground() throws Exception {
                ItemNotaDAO itemDAO = new ItemNotaDAO();
                return itemDAO.findAll();
            }

            @Override
            protected void done() {
                try {
                    List<ItemNota> itensRetornados = get();
                    ItemNotaTableModel tableModel = (ItemNotaTableModel) tableItensNota.getModel();
                    tableModel.clear();
                    tableModel.addList(itensRetornados);
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(ItemNotaFiltrar.this, "Erro ao buscar produtos: " + e.getMessage());
                } finally {
                    // Fecha o diálogo de carregamento
                    loadingDialog.dispose();
                }
            }
        };

        // Inicia o carregamento dos dados
        worker.execute();

        // Exibe o diálogo de carregamento (modal)
        loadingDialog.setVisible(true);
    }

