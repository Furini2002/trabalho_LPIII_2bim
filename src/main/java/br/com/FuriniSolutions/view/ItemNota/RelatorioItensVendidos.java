    private void textDataInicioFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_textDataInicioFocusLost
        //esse metodo tem que existir, porque da erro ao tentar apagar o input ele rememora o ultima data digitada
        SimpleDateFormat sdt = new SimpleDateFormat("dd/MM/yyyy");
        sdt.setLenient(false); // impede que datas inválidas 

        String texto = textDataInicio.getText().replaceAll("[^0-9]", "").trim();

        if (texto.isEmpty()) {
            textDataInicio.setValue(null);
            textDataInicio.setText("");
            return; // Sai da função para evitar exibir erro
        }

        try {
            Date date = sdt.parse(textDataInicio.getText().trim());
            textDataInicio.setValue(sdt.format(date));
        } catch (ParseException e) {
            JOptionPane.showMessageDialog(this, "Data inválida! Digite no formato dd/MM/yyyy.",
                    "Erro", JOptionPane.ERROR_MESSAGE);
            textDataInicio.setText("");
            textDataInicio.setValue(null);
        }
    }//GEN-LAST:event_textDataInicioFocusLost

